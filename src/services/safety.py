# -*- coding: utf-8 -*-
"""위기 신호 선별 — 모델에 보내기 전에 코드가 먼저 판단한다.

**왜 모델에 맡기지 않는가**

2026-10-06 시뮬레이션에서 학생이 "손목을 그었어요"라고 했을 때, 봇은 그걸
연습 부상으로 알아듣고 "오늘 열심히 연습하신 증거"라며 온찜질과 스트레칭을
권했다. 전체 프롬프트가 연습 튜터로 맞춰져 있으니 모델이 그쪽으로 해석한 것이다.

시스템 프롬프트에 "자해를 암시하면 어른에게 연결하라"는 문장은 이미 있었다.
있어도 놓쳤다. 4B 로컬 모델이 매번 알아채리라고 기대하는 건 설계가 아니다.
이 판단만큼은 확률이 아니라 규칙으로 한다 — 놓치면 돌이킬 수 없는 종류의 일이다.

**과하게 잡는 쪽을 택한다.** 연습 이야기를 하려던 학생이 안전 안내를 한 번 더
받는 불편과, 정말 위험한 학생이 스트레칭 조언을 받는 사고는 무게가 다르다.
"""
import re
from typing import Optional

# 직접적인 자해·자살 표현. 하나라도 걸리면 바로 위기로 본다.
_CRISIS_PATTERNS = [
    r"죽고\s*싶", r"죽어\s*버리", r"자살", r"목숨을?\s*끊", r"살기\s*싫",
    r"사라지고\s*싶", r"없어지고\s*싶", r"세상에서\s*사라",
    r"자해", r"손목을?\s*긋", r"손목을?\s*그었", r"칼로\s*그", r"몸에\s*상처를?\s*내",
    r"뛰어내리", r"목을?\s*매", r"극단적\s*선택",
    r"다\s*끝내고\s*싶", r"그만\s*살", r"살아갈\s*이유",
    r"내가\s*없어지면", r"제가\s*없어지면", r"나\s*하나\s*없어도",
]

# 위 표현이 연습 이야기 속에서 비유로 쓰일 수 있는 경우를 걸러낸다.
# 예: "이 곡 연습하다 죽고 싶었다"는 과장이지만, 그래도 한 번 묻는 쪽이 낫다고 보고
# 지금은 예외를 두지 않는다. 오탐 사례가 쌓이면 여기에 추가한다.
_FALSE_POSITIVE_HINTS: list = []

_COMPILED = [re.compile(p) for p in _CRISIS_PATTERNS]


def detect_crisis(message: str) -> Optional[str]:
    """위기 신호가 있으면 걸린 표현을, 없으면 None을 돌려준다."""
    text = (message or "").strip()
    if not text:
        return None
    for pattern in _COMPILED:
        found = pattern.search(text)
        if found:
            if any(hint in text for hint in _FALSE_POSITIVE_HINTS):
                return None
            return found.group(0)
    return None


def crisis_reply(student_name: Optional[str] = None) -> str:
    """위기 신호에 대한 고정 응답.

    연습 조언을 한 줄도 넣지 않는다. 지금 필요한 건 사람이지 메트로놈이 아니다.
    고정 문구로 두는 이유: 이 상황에서 모델이 매번 다른 말을 지어내게 둘 수 없다.
    """
    who = f"{student_name} 학생, " if student_name else ""
    return (
        f"{who}지금 많이 힘드신 것 같아 걱정됩니다. 그 이야기를 꺼내 주셔서 고맙습니다.\n\n"
        "지금은 연습 이야기를 할 때가 아니라고 생각해요. 혼자 견디지 않으셨으면 합니다.\n\n"
        "지금 바로 선생님이나 부모님께, 또는 곁에 있는 어른에게 이 마음을 알려 주세요. "
        "말을 꺼내기 어렵다면 아래로 전화하셔도 됩니다. 24시간 받습니다.\n\n"
        "- 자살예방 상담전화 109\n"
        "- 청소년 상담전화 1388\n\n"
        "만약 지금 당장 위험한 상황이라면 112 또는 119로 연락해 주세요.\n\n"
        "저는 연습을 도와주는 역할이라 여기까지밖에 못 하지만, "
        "선생님께는 이 이야기를 꼭 전해 주시면 좋겠습니다."
    )
