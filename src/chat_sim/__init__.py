"""AI 상담 챗봇 시뮬레이터 — 학생이 할 법한 말 1만 가지를 실제로 물어보고 기록한다.

**왜 만드는가**

상담 봇은 학생과 단둘이 대화한다. 선생님도 우리도 그 자리에 없다. 그래서 봇이
클래식 교재를 권하거나, 전공을 되묻거나, 자해를 암시한 학생에게 연습 조언을
하더라도 **아무도 모른 채 지나간다**. 문제가 드러나는 건 사고가 난 뒤다.

그래서 학생이 할 법한 말을 미리 대량으로 던져보고, 답을 전부 저장해 두고,
기계적으로 검사한다. 1만 건을 돌리면 드물게 터지는 실패도 몇 건은 잡힌다.

**구성**

- `scenarios.py` : 시나리오 1만 건을 조합으로 만든다(전공 x 상황 x 의도 x 말투).
- `checks.py`    : 답변 한 건을 규칙으로 채점한다(클래식 금지, 이모지 금지 등).
- `repository.py`: 결과를 `logs/chat_sim.db`에 쌓는다. 운영 DB는 건드리지 않는다.
- `runner.py`    : 중단/재개가 되는 배치 실행기.

**운영 DB를 쓰지 않는 이유**: 1만 건이면 `ai_usage_log`에 1만 행이 쌓이고
학생 통계가 오염된다. QA 에이전트가 `logs/qa_agent.db`를 따로 쓰는 것과 같은 이유다.
"""
